// The JavaScript bundles: the vanilla scripts of ui/static joined into one
// minified file per context, so that a page loads its code in one request.
// scripts/build-assets.mjs writes them, and ui/admin/test/bundles.test.mjs
// checks that the committed files match their sources.
//
// Each bundle is an IIFE (a classic script, loaded with defer) that runs its
// sources in the order listed, each still in its own scope. A source runs
// only where it has something to do: it looks for its elements first.
// Basecoat's files stay as they are, already minified, and so do the scripts
// one admin page needs (editor, builder, customizer, passkey) and the two
// that must run before the first paint (theme-init.js, nav-groups.js).
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const bundles = [
  {
    // Every public page (shared/head): the toggles and menus, the cookie
    // consent (only with its dialog on the page; window.sapConsent is ready
    // before the plugins' scripts run), the one-page menu (only with
    // data-sap-onepage on the bundle's script tag), the video players, the
    // site assistant and the pricing table's monthly/yearly switch.
    name: "site",
    out: "ui/static/site.min.js",
    sources: ["site.js", "consent.js", "onepage.js", "video.js", "assistant.js", "plans.js"],
  },
  {
    // The chrome of every admin page (ui/admin/templates/layout.html), after
    // Basecoat's scripts.
    name: "admin",
    out: "ui/static/admin.min.js",
    sources: ["selects.js", "admin.js", "autosave.js", "jobs.js", "ai.js", "updates.js"],
  },
];

// The whole bundle is strict: selects.js was a module, which is strict
// without saying so, and the others are strict already.
const banner = (b) =>
  `/* sap13ns ${b.name} bundle: ${b.sources.join(", ")} (ui/static). Generated by npm run build: edit the sources. */\n"use strict";`;

// options returns esbuild's options for one bundle. The syntax is kept as
// written (no target): esbuild only joins, renames and drops whitespace.
export function options(root, b) {
  return {
    stdin: {
      contents: b.sources.map((s) => `import "./${s}";`).join("\n"),
      resolveDir: join(root, "ui/static"),
      sourcefile: `${b.name}.bundle.js`,
      loader: "js",
    },
    bundle: true,
    format: "iife",
    minify: true,
    charset: "utf8",
    legalComments: "none",
    banner: { js: banner(b) },
    outfile: join(root, b.out),
    logLevel: "warning",
  };
}

// sources lists the files of a bundle, for watch mode and the test.
export const sourcePaths = (root, b) => b.sources.map((s) => join(root, "ui/static", s));

// committed reads a bundle as it is on disk.
export const committed = (root, b) => readFileSync(join(root, b.out), "utf8");
